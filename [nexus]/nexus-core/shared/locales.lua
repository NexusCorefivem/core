local function normalizeLocale(locale)
    if type(locale) ~= "string" then
        return NexusConfig.Framework.defaultLocale
    end

    locale = locale:lower()
    for _, supported in ipairs(NexusConfig.Framework.supportedLocales) do
        if locale == supported then
            return locale
        end
    end

    return NexusConfig.Framework.defaultLocale
end

function NexusGetSupportedLocales()
    return NexusConfig.Framework.supportedLocales
end

function NexusNormalizeLocale(locale)
    return normalizeLocale(locale)
end

function NexusTranslate(locale, key, ...)
    local resolvedLocale = normalizeLocale(locale)
    local template = NexusLocales[resolvedLocale] and NexusLocales[resolvedLocale][key]

    if not template then
        template = NexusLocales[NexusConfig.Framework.defaultLocale] and NexusLocales[NexusConfig.Framework.defaultLocale][key]
    end

    if not template then
        return key
    end

    if select("#", ...) > 0 then
        return template:format(...)
    end

    return template
end
